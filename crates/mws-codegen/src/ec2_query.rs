//! ec2Query server generation (EC2): form-encoded requests whose keys come
//! from `ec2QueryName` (or a capitalized `xmlName` / member name) with every
//! list flattened, and XML responses without a `Result` wrapper.
//!
//! Spec: <https://smithy.io/2.0/aws/protocols/aws-ec2-query-protocol.html>

use std::collections::BTreeSet;
use std::fmt::Write;

use mws_smithy::{Member, Model, Shape, ShapeType};
use serde_json::Value;

use crate::common::{self, de_fn_name, qualified_type, ser_fn_name};
use crate::naming::{rust_str, snake_case, type_name};
use crate::rust_types::{field_name, presence, Presence, TypeGen};
use crate::xml_ser::XmlSer;

/// Options for [`generate`].
#[derive(Debug, Clone, Default)]
pub struct Ec2QueryOptions {
    /// Generate types, codecs and handler methods only for these
    /// operations (EC2's model has over 800, and compiling all of them
    /// takes many minutes). The others still dispatch, answering
    /// `NotImplemented`. `None` generates everything.
    pub operations: Option<Vec<String>>,
}

pub fn generate(model: &Model, options: &Ec2QueryOptions) -> String {
    Gen { model, types: TypeGen::new(model), out: String::new(), options }.run()
}

/// The request key of a member: `ec2QueryName`, else `xmlName` with its
/// first letter upper-cased, else the member name likewise.
pub fn query_key(m: &Member) -> String {
    if let Some(n) = m.get_trait("aws.protocols#ec2QueryName").and_then(Value::as_str) {
        return n.to_string();
    }
    let base = m.get_trait("xmlName").and_then(Value::as_str).unwrap_or(&m.name);
    let mut c = base.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

struct Gen<'m> {
    model: &'m Model,
    types: TypeGen<'m>,
    out: String,
    options: &'m Ec2QueryOptions,
}

impl<'m> Gen<'m> {
    fn run(mut self) -> String {
        let model = self.model;
        let service = model.service().expect("model has a service");
        assert!(service.has_trait("aws.protocols#ec2Query"), "{} does not use the ec2Query protocol", service.id);
        let all_ops = model.operations(service);
        if let Some(wanted) = &self.options.operations {
            for w in wanted {
                assert!(all_ops.iter().any(|o| o.name() == w), "{} has no operation {w}", service.id);
            }
        }
        let ops: Vec<&Shape> = all_ops
            .iter()
            .copied()
            .filter(|o| self.options.operations.as_ref().is_none_or(|w| w.iter().any(|n| n == o.name())))
            .collect();
        let namespace = service
            .get_trait("xmlNamespace")
            .and_then(|v| v.get("uri"))
            .and_then(Value::as_str)
            .expect("ec2Query services declare an xmlNamespace");
        let version = service.version.clone().unwrap_or_default();

        let inputs: Vec<String> = ops.iter().filter_map(|o| o.input.clone()).collect();
        let outputs: Vec<String> = ops.iter().filter_map(|o| o.output.clone()).collect();
        let input_closure = self.types.closure(inputs);
        let output_closure = self.types.closure(outputs);
        let all: BTreeSet<String> = input_closure.union(&output_closure).cloned().collect();

        let w = &mut self.out;
        let _ = writeln!(w, "// @generated by mws-codegen from {}. Do not edit.", service.id);
        let _ = writeln!(w, "use ::mws_proto_ec2::__private::{{async_trait, chrono}};");
        let _ = writeln!(w, "use ::mws_proto_ec2::{{Decoder, Params, ServiceInfo, XmlWriter}};");
        let _ = writeln!(w, "use ::mws_core::{{HttpResponse, RequestContext, ServiceError}};");
        let _ = writeln!(w);
        let _ = writeln!(
            w,
            "pub const SERVICE_INFO: ServiceInfo = ServiceInfo {{ xml_namespace: {}, version: {} }};",
            rust_str(namespace),
            rust_str(&version)
        );
        let _ = writeln!(
            w,
            "/// Every operation in the model, by wire name.\npub const OPERATIONS: &[&str] = &[{}];",
            all_ops.iter().map(|o| rust_str(o.name())).collect::<Vec<_>>().join(", ")
        );

        let _ = writeln!(w, "\npub mod types {{\n    use super::chrono;");
        let mut types_src = String::new();
        self.types.emit_types(&all, &mut types_src);
        self.out.push_str(&types_src);
        let _ = writeln!(self.out, "}}");

        // EC2 models no errors; handlers build them from their codes.
        common::emit_handler(model, &ops, &mut self.out);
        self.emit_dispatch(&ops);

        let mut de = String::new();
        for id in &input_closure {
            let s = model.expect(id);
            match s.ty {
                ShapeType::Structure | ShapeType::Union => self.emit_de_aggregate(s, &mut de),
                ShapeType::List | ShapeType::Set => self.emit_de_list(s, &mut de),
                ShapeType::Map => panic!("ec2Query has no map serialization ({})", s.id),
                _ => {}
            }
        }
        let _ = writeln!(self.out, "\n#[allow(unused_variables, unused_mut, clippy::all)]\nmod de {{");
        let _ = writeln!(self.out, "    use super::*;");
        self.out.push_str(&de);
        let _ = writeln!(self.out, "}}");

        let mut ser = String::new();
        XmlSer { model, types: &self.types }.emit_all(&output_closure, &mut ser);
        let _ = writeln!(self.out, "\n#[allow(unused_variables, clippy::all)]\nmod ser {{\n    use super::*;");
        self.out.push_str(&ser);
        let _ = writeln!(self.out, "}}");

        crate::json_codec::emit_invoke(model, &ops, "json_de", "json_ser", "InvalidParameterValue", &mut self.out);
        let mut codec = crate::json_codec::JsonCodec::new(model, &self.types);
        let de = codec.de_module(&input_closure, "json_de");
        let ser = codec.ser_module(&output_closure, "json_ser");
        self.out.push_str(&de);
        self.out.push_str(&ser);
        self.out
    }

    fn emit_dispatch(&mut self, ops: &[&Shape]) {
        let mut w = String::new();
        let _ = writeln!(
            w,
            "\n/// Decode `params`, run the matching handler method, and encode the result.\npub async fn dispatch<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, params: &Params) -> HttpResponse {{"
        );
        let _ = writeln!(w, "    let rid = ctx.request_id.as_str();");
        let _ = writeln!(w, "    let result: Result<String, ServiceError> = match params.get(\"Action\") {{");
        let _ = writeln!(w, "        None => Err(::mws_proto_ec2::missing_action()),");
        for op in ops {
            let name = op.name();
            let method = crate::naming::ident(&snake_case(name));
            let _ = writeln!(w, "        Some({}) => {{", rust_str(name));
            match &op.input {
                Some(i) => {
                    let de_fn = de_fn_name(self.model.expect(i));
                    let _ = writeln!(w, "            let mut d = Decoder::new(params);");
                    let _ = writeln!(w, "            let input = de::{de_fn}(&mut d, \"\").unwrap_or_default();");
                    let _ = writeln!(w, "            match d.finish() {{");
                    let _ = writeln!(w, "                Err(e) => Err(e),");
                    let _ = writeln!(w, "                Ok(()) => handler.{method}(ctx, input).await,");
                    let _ = writeln!(w, "            }}");
                }
                None => {
                    let _ = writeln!(w, "            handler.{method}(ctx, ()).await");
                }
            }
            match &op.output {
                Some(o) => {
                    let ser_fn = ser_fn_name(self.model.expect(o));
                    let _ = writeln!(
                        w,
                        "            .map(|out| ::mws_proto_ec2::success_body(&SERVICE_INFO, {}, rid, Some(&|w: &mut XmlWriter| ser::{ser_fn}(w, &out))))",
                        rust_str(name)
                    );
                }
                None => {
                    let _ = writeln!(
                        w,
                        "            .map(|()| ::mws_proto_ec2::success_body(&SERVICE_INFO, {}, rid, None))",
                        rust_str(name)
                    );
                }
            }
            let _ = writeln!(w, "        }}");
        }
        let _ = writeln!(
            w,
            "        Some(other) if OPERATIONS.contains(&other) => Err(ServiceError::not_implemented(other)),"
        );
        let _ = writeln!(w, "        Some(other) => Err(::mws_proto_ec2::invalid_action(other)),");
        let _ = writeln!(w, "    }};");
        let _ = writeln!(w, "    match result {{");
        let _ = writeln!(w, "        Ok(body) => ::mws_proto_ec2::xml_response(200, rid, body),");
        let _ = writeln!(w, "        Err(e) => ::mws_proto_ec2::error_response(rid, &e),");
        let _ = writeln!(w, "    }}\n}}");
        self.out.push_str(&w);
    }

    /// Expression of type `Option<T>` decoding `target` at key var `k`.
    fn de_expr(&self, target: &str) -> String {
        let s = self.model.expect(target);
        match s.ty {
            ShapeType::String
            | ShapeType::Enum
            | ShapeType::BigInteger
            | ShapeType::BigDecimal
            | ShapeType::Document => "d.string(&k)".into(),
            ShapeType::Boolean => "d.boolean(&k)".into(),
            ShapeType::Byte => "d.number::<i8>(&k)".into(),
            ShapeType::Short => "d.number::<i16>(&k)".into(),
            ShapeType::Integer | ShapeType::IntEnum => "d.number::<i32>(&k)".into(),
            ShapeType::Long => "d.number::<i64>(&k)".into(),
            ShapeType::Float => "d.number::<f32>(&k)".into(),
            ShapeType::Double => "d.number::<f64>(&k)".into(),
            ShapeType::Timestamp => "d.timestamp(&k)".into(),
            ShapeType::Blob => "d.blob(&k)".into(),
            _ => format!("{}(d, &k)", de_fn_name(s)),
        }
    }

    fn emit_de_aggregate(&self, s: &Shape, w: &mut String) {
        let ty = type_name(s.name());
        let is_union = s.ty == ShapeType::Union;
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str) -> Option<types::{ty}> {{",
            de_fn_name(s)
        );
        let _ = writeln!(w, "        if !key.is_empty() && !d.has_prefix(key) {{ return None; }}");
        if is_union {
            let _ = writeln!(w, "        let mut out: Option<types::{ty}> = None;");
        } else {
            let _ = writeln!(w, "        let mut out = types::{ty}::default();");
        }
        for m in &s.members {
            let wire = query_key(m);
            let _ = writeln!(w, "        {{");
            let _ = writeln!(
                w,
                "            let k = if key.is_empty() {{ {}.to_string() }} else {{ format!(\"{{key}}.{wire}\") }};",
                rust_str(&wire)
            );
            let _ = writeln!(w, "            let val = {};", self.de_expr(&m.target));
            let boxed = self.types.is_boxed(&s.id, &m.target);
            let wrap = |e: &str| if boxed { format!("::std::boxed::Box::new({e})") } else { e.to_string() };
            let field = field_name(m);
            if is_union {
                let _ = writeln!(
                    w,
                    "            if out.is_none() {{ if let Some(v) = val {{ out = Some(types::{ty}::{}({})); }} }}",
                    type_name(&m.name),
                    wrap("v")
                );
            } else {
                match presence(m) {
                    Presence::Required => {
                        let _ = writeln!(w, "            d.required(&val, &k);");
                        let _ = writeln!(w, "            if let Some(v) = val {{ out.{field} = {}; }}", wrap("v"));
                    }
                    Presence::Defaulted => {
                        let _ = writeln!(w, "            if let Some(v) = val {{ out.{field} = {}; }}", wrap("v"));
                    }
                    Presence::Optional => {
                        let _ = writeln!(w, "            out.{field} = val.map(|v| {});", wrap("v"));
                    }
                }
            }
            let _ = writeln!(w, "        }}");
        }
        if is_union {
            let _ = writeln!(w, "        out");
        } else {
            let _ = writeln!(w, "        Some(out)");
        }
        let _ = writeln!(w, "    }}");
    }

    fn emit_de_list(&self, s: &Shape, w: &mut String) {
        let member = s.member.clone().unwrap();
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str) -> Option<{}> {{",
            de_fn_name(s),
            qualified_type(self.model, &s.id)
        );
        // Lists are always flattened: `Key.1`, `Key.2`, ...
        let _ = writeln!(w, "        let idx = d.indexes(key);");
        let _ = writeln!(w, "        if idx.is_empty() {{ return None; }}");
        let _ = writeln!(w, "        let mut out = Vec::with_capacity(idx.len());");
        let _ = writeln!(w, "        for i in idx {{");
        let _ = writeln!(w, "            let k = format!(\"{{key}}.{{i}}\");");
        let _ = writeln!(w, "            if let Some(v) = {} {{ out.push(v); }}", self.de_expr(&member.target));
        let _ = writeln!(w, "        }}");
        let _ = writeln!(w, "        Some(out)");
        let _ = writeln!(w, "    }}");
    }
}
