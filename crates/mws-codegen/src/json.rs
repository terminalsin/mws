//! awsJson1.0 / awsJson1.1 server generation: `X-Amz-Target` dispatch, JSON
//! decoding with validation, JSON encoding, the handler trait and errors.

use std::collections::BTreeSet;
use std::fmt::Write;

use mws_smithy::{Model, Shape};

use crate::common::{self, de_fn_name, ser_fn_name};
use crate::json_codec::{self, JsonCodec};
use crate::naming::{rust_str, snake_case};
use crate::rust_types::TypeGen;

/// Per-service options that the model does not carry.
#[derive(Debug, Clone)]
pub struct JsonOptions {
    /// Error code for constraint violations.
    pub validation_error: &'static str,
}

impl Default for JsonOptions {
    fn default() -> Self {
        Self { validation_error: "ValidationException" }
    }
}

const RT: &str = "::mws_proto_json";

pub fn generate(model: &Model, options: &JsonOptions) -> String {
    Gen { model, types: TypeGen::new(model), options }.run()
}

fn encode_event_fn(union: &Shape) -> String {
    format!("encode_event_{}", snake_case(union.name()))
}

struct Gen<'m, 'o> {
    model: &'m Model,
    types: TypeGen<'m>,
    options: &'o JsonOptions,
}

impl Gen<'_, '_> {
    fn run(self) -> String {
        let model = self.model;
        let service = model.service().expect("model has a service");
        let content_type = if service.has_trait("aws.protocols#awsJson1_1") {
            "application/x-amz-json-1.1"
        } else if service.has_trait("aws.protocols#awsJson1_0") {
            "application/x-amz-json-1.0"
        } else {
            panic!("{} does not use an awsJson protocol", service.id)
        };
        let ops = model.operations(service);
        let inputs: Vec<String> = ops.iter().filter_map(|o| o.input.clone()).collect();
        let outputs: Vec<String> = ops.iter().filter_map(|o| o.output.clone()).collect();
        let input_closure = self.types.closure(inputs);
        let output_closure = self.types.closure(outputs);
        let all: BTreeSet<String> = input_closure.union(&output_closure).cloned().collect();

        let mut out = String::new();
        let w = &mut out;
        let _ = writeln!(w, "// @generated by mws-codegen from {}. Do not edit.", service.id);
        let _ = writeln!(w, "use {RT}::__private::{{async_trait, chrono}};");
        let _ = writeln!(w, "#[allow(unused_imports)]\nuse {RT}::{{Decoder, Map, ServiceInfo, Value}};");
        let _ = writeln!(w, "use ::mws_core::{{HttpRequest, HttpResponse, RequestContext, ServiceError}};");
        let query_compatible = if service.has_trait("aws.protocols#awsQueryCompatible") {
            let errors = common::all_errors(service, &model.operations(service));
            let pairs: Vec<String> = common::query_compatible_codes(model, &errors)
                .iter()
                .map(|(shape, code)| format!("({}, {})", rust_str(shape), rust_str(code)))
                .collect();
            let namespace = service.id.split('#').next().unwrap_or_default();
            format!(
                "Some(::mws_proto_json::QueryCompatible {{ namespace: {}, codes: &[{}] }})",
                rust_str(namespace),
                pairs.join(", ")
            )
        } else {
            "None".to_string()
        };
        let _ = writeln!(
            w,
            "\npub const SERVICE_INFO: ServiceInfo = ServiceInfo {{ target_prefix: {}, content_type: {}, validation_error: {}, query_compatible: {query_compatible} }};",
            rust_str(service.name()),
            rust_str(content_type),
            rust_str(self.options.validation_error)
        );
        let _ = writeln!(
            w,
            "/// Every operation in the model, by wire name.\npub const OPERATIONS: &[&str] = &[{}];",
            ops.iter().map(|o| rust_str(o.name())).collect::<Vec<_>>().join(", ")
        );
        let _ = writeln!(w, "\npub mod types {{\n    use super::chrono;");
        self.types.emit_types(&all, w);
        let _ = writeln!(w, "}}");
        // awsJson ignores `awsQueryError` codes (KMS models them but answers
        // with shape names) unless the service is `awsQueryCompatible`:
        // then the shape name goes in `__type` and the query code in the
        // `x-amzn-query-error` header.
        let errors = common::all_errors(service, &ops);
        let codes = if service.has_trait("aws.protocols#awsQueryCompatible") {
            common::ErrorCodes::QueryCompatible
        } else {
            common::ErrorCodes::Shape
        };
        common::emit_errors(model, &errors, codes, w);
        common::emit_handler(model, &ops, w);
        self.emit_dispatch(&ops, w);

        json_codec::emit_invoke(model, &ops, "de", "ser", self.options.validation_error, &mut out);
        if service.has_trait("smithy.protocols#rpcv2Cbor") {
            emit_cbor(model, service, &ops, &output_closure, &mut out);
        }
        let mut codec = JsonCodec::new(model, &self.types);
        out.push_str(&codec.de_module(&input_closure, "de"));
        out.push_str(&codec.ser_module(&output_closure, "ser"));
        out
    }

    fn emit_dispatch(&self, ops: &[&Shape], w: &mut String) {
        let _ = writeln!(
            w,
            "\n/// Decode the request, run the matching handler method, and encode the result.\npub async fn dispatch<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, req: &HttpRequest) -> HttpResponse {{"
        );
        let _ = writeln!(w, "    match route(handler, ctx, req).await {{");
        let _ = writeln!(
            w,
            "        Ok({RT}::Reply::Json(v)) => {RT}::json_response(&SERVICE_INFO, &ctx.request_id, 200, Some(v)),"
        );
        let _ = writeln!(
            w,
            "        Ok({RT}::Reply::EventStream(b)) => {RT}::event_stream_response(&SERVICE_INFO, &ctx.request_id, b),"
        );
        let _ = writeln!(w, "        Err(e) => {RT}::error_response(&SERVICE_INFO, &ctx.request_id, &e),");
        let _ = writeln!(w, "    }}\n}}");
        let _ = writeln!(w, "\n#[allow(unused_mut, clippy::all)]\nasync fn route<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, req: &HttpRequest) -> Result<{RT}::Reply, ServiceError> {{");
        let _ = writeln!(w, "    let op = {RT}::operation(&SERVICE_INFO, req)?;");
        let _ = writeln!(w, "    match op {{");
        for op in ops {
            let _ = writeln!(w, "        {} => {{", rust_str(op.name()));
            match &op.input {
                Some(i) => {
                    let _ = writeln!(w, "            let body = {RT}::parse_body(req.body())?;");
                    let _ = writeln!(w, "            let mut d = Decoder::new();");
                    let _ = writeln!(
                        w,
                        "            let input = de::{}(&mut d, Some(&body), \"\").unwrap_or_default();",
                        de_fn_name(self.model.expect(i))
                    );
                    let _ = writeln!(w, "            d.finish(SERVICE_INFO.validation_error)?;");
                    let _ = writeln!(w, "            let out = {}?;", crate::common::handler_call(op, "input"));
                }
                None => {
                    let _ = writeln!(w, "            let out = {}?;", crate::common::handler_call(op, "()"));
                }
            }
            match &op.output {
                Some(o) => match self.event_stream_member(o) {
                    Some((field, union)) => {
                        let _ = writeln!(
                            w,
                            "            let mut stream = Vec::new();\n            for ev in &out.{field} {{ stream.extend({}(ev)); }}\n            Ok({RT}::Reply::EventStream(stream))",
                            encode_event_fn(union)
                        );
                    }
                    None => {
                        let _ = writeln!(
                            w,
                            "            Ok({RT}::Reply::Json(ser::{}(&out)))",
                            ser_fn_name(self.model.expect(o))
                        );
                    }
                },
                None => {
                    let _ = writeln!(
                        w,
                        "            let () = out;\n            Ok({RT}::Reply::Json(Value::Object(Map::new())))"
                    );
                }
            }
            let _ = writeln!(w, "        }}");
        }
        let _ = writeln!(w, "        other => Err({RT}::unknown_operation(other)),");
        let _ = writeln!(w, "    }}\n}}");
        self.emit_event_stream_helpers(ops, w);
        let _ = writeln!(
            w,
            "\n/// The operation a request addresses, if any.\npub fn operation_for(req: &HttpRequest) -> Option<&str> {{ {RT}::operation(&SERVICE_INFO, req).ok() }}"
        );
    }

    /// The output member holding an event stream, and the stream's union.
    fn event_stream_member(&self, output: &str) -> Option<(String, &Shape)> {
        let o = self.model.expect(output);
        o.members.iter().find_map(|m| {
            let t = self.model.expect(&m.target);
            (t.ty == mws_smithy::ShapeType::Union && t.has_trait("streaming"))
                .then(|| (crate::rust_types::field_name(m), t))
        })
    }

    /// For each operation with an event stream output: a public encoder
    /// for one event (so a service can keep a stream open and send events
    /// as they happen) and a public decoder for the operation's input.
    fn emit_event_stream_helpers(&self, ops: &[&Shape], w: &mut String) {
        let model = self.model;
        for op in ops {
            let Some((field, union)) = op.output.as_deref().and_then(|o| self.event_stream_member(o)) else { continue };
            let output = model.expect(op.output.as_deref().unwrap());
            assert!(
                output.members.len() == 1,
                "{}: event stream outputs with other members (initial-response) are not supported yet",
                op.id
            );
            let _ = field;
            let ty = crate::naming::type_name(union.name());
            let mut arms = String::new();
            for m in &union.members {
                let event = model.expect(&m.target);
                for e in &event.members {
                    assert!(
                        !e.has_trait("eventPayload") && !e.has_trait("eventHeader"),
                        "{}${}: bound event members are not supported yet",
                        event.id,
                        e.name
                    );
                }
                let deref = if self.types.is_boxed(&union.id, &m.target) { "&**x" } else { "x" };
                let body = format!("ser::{}({deref}).to_string()", ser_fn_name(event));
                let encode = if event.has_trait("error") {
                    format!(
                        "::mws_core::eventstream::exception({}, \"application/json\", {body}.as_bytes())",
                        rust_str(&m.name)
                    )
                } else {
                    format!(
                        "::mws_core::eventstream::event({}, Some(\"application/json\"), {body}.as_bytes())",
                        rust_str(&m.name)
                    )
                };
                let _ = writeln!(arms, "        types::{ty}::{}(x) => {encode},", crate::naming::type_name(&m.name));
            }
            let _ = writeln!(
                w,
                "\n/// One `{}` event as an `application/vnd.amazon.eventstream` message.\npub fn {}(ev: &types::{ty}) -> Vec<u8> {{\n    match ev {{\n{arms}    }}\n}}",
                union.name(),
                encode_event_fn(union)
            );
            if let Some(i) = &op.input {
                let input = model.expect(i);
                let _ = writeln!(
                    w,
                    "\n/// Decode and validate a `{}` request.\npub fn decode_input_{}(req: &HttpRequest) -> Result<types::{}, ServiceError> {{\n    let body = {RT}::parse_body(req.body())?;\n    let mut d = Decoder::new();\n    let input = de::{}(&mut d, Some(&body), \"\").unwrap_or_default();\n    d.finish(SERVICE_INFO.validation_error)?;\n    Ok(input)\n}}",
                    op.name(),
                    snake_case(op.name()),
                    crate::naming::type_name(input.name()),
                    de_fn_name(input)
                );
            }
        }
    }
}

/// rpcv2Cbor on top of the awsJson document model: a table of the output
/// shapes (where timestamps, blobs and floats sit, which CBOR encodes
/// differently from JSON) and `dispatch_cbor`, which runs requests through
/// `invoke`.
fn emit_cbor(model: &Model, service: &Shape, ops: &[&Shape], closure: &BTreeSet<String>, w: &mut String) {
    use mws_smithy::ShapeType;
    let index: std::collections::BTreeMap<&str, usize> =
        closure.iter().enumerate().map(|(i, id)| (id.as_str(), i)).collect();
    let _ = writeln!(
        w,
        "\n/// The output shapes, for rpcv2Cbor encoding.\npub static CBOR_SHAPES: &[::mws_proto_cbor::Kind] = &["
    );
    for id in closure {
        let s = model.expect(id);
        let kind = match s.ty {
            ShapeType::Structure | ShapeType::Union => {
                let members: Vec<String> = s
                    .members
                    .iter()
                    .map(|m| format!("({}, {})", rust_str(&m.name), index[m.target.as_str()]))
                    .collect();
                format!("Struct(&[{}])", members.join(", "))
            }
            ShapeType::List | ShapeType::Set => {
                format!("List({})", index[s.member.as_ref().expect("list member").target.as_str()])
            }
            ShapeType::Map => format!("Map({})", index[s.value.as_ref().expect("map value").target.as_str()]),
            ShapeType::Timestamp => "Timestamp".into(),
            ShapeType::Blob => "Blob".into(),
            ShapeType::Float => "Float".into(),
            ShapeType::Double => "Double".into(),
            _ => "Plain".into(),
        };
        let _ = writeln!(w, "    ::mws_proto_cbor::Kind::{kind}, // {id}");
    }
    let _ = writeln!(w, "];");
    let _ = writeln!(w, "\n/// The `CBOR_SHAPES` entry of an operation's output; `None` for no output.\npub fn cbor_output(operation: &str) -> Option<usize> {{\n    match operation {{");
    for op in ops {
        if let Some(o) = &op.output {
            let _ = writeln!(w, "        {} => Some({}),", rust_str(op.name()), index[o.as_str()]);
        }
    }
    let _ = writeln!(w, "        _ => None,\n    }}\n}}");
    let _ = writeln!(
        w,
        "\n/// The `{{ServiceName}}` of rpcv2Cbor request paths.\npub const CBOR_SERVICE: &str = {};",
        rust_str(service.name())
    );
    let _ = writeln!(
        w,
        r#"
/// Decode an rpcv2Cbor request, run the matching handler method, and encode the result.
pub async fn dispatch_cbor<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, req: &HttpRequest) -> HttpResponse {{
    let run = async {{
        let op = ::mws_proto_cbor::operation(CBOR_SERVICE, req)?;
        let body = ::mws_proto_cbor::decode_body(req.body())?;
        let out = invoke(handler, ctx, op, body).await?;
        Ok::<_, ServiceError>((op, out))
    }};
    match run.await {{
        Ok((op, out)) => {{
            let body = cbor_output(op).map(|root| ::mws_proto_cbor::encode(&out, CBOR_SHAPES, root));
            ::mws_proto_cbor::response(&ctx.request_id, body)
        }}
        Err(e) => ::mws_proto_cbor::error_response(&SERVICE_INFO, &ctx.request_id, &e),
    }}
}}"#
    );
}
