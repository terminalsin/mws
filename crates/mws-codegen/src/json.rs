//! awsJson1.0 / awsJson1.1 server generation: `X-Amz-Target` dispatch, JSON
//! decoding with validation, JSON encoding, the handler trait and errors.

use std::collections::BTreeSet;
use std::fmt::Write;

use mws_smithy::{Model, Shape};

use crate::common::{self, de_fn_name, ser_fn_name};
use crate::json_codec::{self, JsonCodec};
use crate::naming::{ident, rust_str, snake_case};
use crate::rust_types::TypeGen;

/// Per-service options that the model does not carry.
#[derive(Debug, Clone)]
pub struct JsonOptions {
    /// Error code for constraint violations.
    pub validation_error: &'static str,
}

impl Default for JsonOptions {
    fn default() -> Self {
        Self { validation_error: "ValidationException" }
    }
}

const RT: &str = "::mws_proto_json";

pub fn generate(model: &Model, options: &JsonOptions) -> String {
    Gen { model, types: TypeGen::new(model), options }.run()
}

struct Gen<'m, 'o> {
    model: &'m Model,
    types: TypeGen<'m>,
    options: &'o JsonOptions,
}

impl Gen<'_, '_> {
    fn run(self) -> String {
        let model = self.model;
        let service = model.service().expect("model has a service");
        let content_type = if service.has_trait("aws.protocols#awsJson1_1") {
            "application/x-amz-json-1.1"
        } else if service.has_trait("aws.protocols#awsJson1_0") {
            "application/x-amz-json-1.0"
        } else {
            panic!("{} does not use an awsJson protocol", service.id)
        };
        let ops = model.operations(service);
        let inputs: Vec<String> = ops.iter().filter_map(|o| o.input.clone()).collect();
        let outputs: Vec<String> = ops.iter().filter_map(|o| o.output.clone()).collect();
        let input_closure = self.types.closure(inputs);
        let output_closure = self.types.closure(outputs);
        let all: BTreeSet<String> = input_closure.union(&output_closure).cloned().collect();

        let mut out = String::new();
        let w = &mut out;
        let _ = writeln!(w, "// @generated by mws-codegen from {}. Do not edit.", service.id);
        let _ = writeln!(w, "use {RT}::__private::{{async_trait, chrono}};");
        let _ = writeln!(w, "#[allow(unused_imports)]\nuse {RT}::{{Decoder, Map, ServiceInfo, Value}};");
        let _ = writeln!(w, "use ::mws_core::{{HttpRequest, HttpResponse, RequestContext, ServiceError}};");
        let _ = writeln!(
            w,
            "\npub const SERVICE_INFO: ServiceInfo = ServiceInfo {{ target_prefix: {}, content_type: {}, validation_error: {} }};",
            rust_str(service.name()),
            rust_str(content_type),
            rust_str(self.options.validation_error)
        );
        let _ = writeln!(
            w,
            "/// Every operation in the model, by wire name.\npub const OPERATIONS: &[&str] = &[{}];",
            ops.iter().map(|o| rust_str(o.name())).collect::<Vec<_>>().join(", ")
        );
        let _ = writeln!(w, "\npub mod types {{\n    use super::chrono;");
        self.types.emit_types(&all, w);
        let _ = writeln!(w, "}}");
        common::emit_errors(model, &common::all_errors(service, &ops), w);
        common::emit_handler(model, &ops, w);
        self.emit_dispatch(&ops, w);

        json_codec::emit_invoke(model, &ops, "de", "ser", self.options.validation_error, &mut out);
        let mut codec = JsonCodec::new(model, &self.types);
        out.push_str(&codec.de_module(&input_closure, "de"));
        out.push_str(&codec.ser_module(&output_closure, "ser"));
        out
    }

    fn emit_dispatch(&self, ops: &[&Shape], w: &mut String) {
        let _ = writeln!(
            w,
            "\n/// Decode the request, run the matching handler method, and encode the result.\npub async fn dispatch<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, req: &HttpRequest) -> HttpResponse {{"
        );
        let _ = writeln!(w, "    match route(handler, ctx, req).await {{");
        let _ = writeln!(w, "        Ok(v) => {RT}::json_response(&SERVICE_INFO, &ctx.request_id, 200, Some(v)),");
        let _ = writeln!(w, "        Err(e) => {RT}::error_response(&SERVICE_INFO, &ctx.request_id, &e),");
        let _ = writeln!(w, "    }}\n}}");
        let _ = writeln!(w, "\n#[allow(unused_mut, clippy::all)]\nasync fn route<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, req: &HttpRequest) -> Result<Value, ServiceError> {{");
        let _ = writeln!(w, "    let op = {RT}::operation(&SERVICE_INFO, req)?;");
        let _ = writeln!(w, "    match op {{");
        for op in ops {
            let method = ident(&snake_case(op.name()));
            let _ = writeln!(w, "        {} => {{", rust_str(op.name()));
            match &op.input {
                Some(i) => {
                    let _ = writeln!(w, "            let body = {RT}::parse_body(req.body())?;");
                    let _ = writeln!(w, "            let mut d = Decoder::new();");
                    let _ = writeln!(
                        w,
                        "            let input = de::{}(&mut d, Some(&body), \"\").unwrap_or_default();",
                        de_fn_name(self.model.expect(i))
                    );
                    let _ = writeln!(w, "            d.finish(SERVICE_INFO.validation_error)?;");
                    let _ = writeln!(w, "            let out = handler.{method}(ctx, input).await?;");
                }
                None => {
                    let _ = writeln!(w, "            let out = handler.{method}(ctx, ()).await?;");
                }
            }
            match &op.output {
                Some(o) => {
                    let _ = writeln!(w, "            Ok(ser::{}(&out))", ser_fn_name(self.model.expect(o)));
                }
                None => {
                    let _ = writeln!(w, "            let () = out;\n            Ok(Value::Object(Map::new()))");
                }
            }
            let _ = writeln!(w, "        }}");
        }
        let _ = writeln!(w, "        other => Err({RT}::unknown_operation(other)),");
        let _ = writeln!(w, "    }}\n}}");
        let _ = writeln!(
            w,
            "\n/// The operation a request addresses, if any.\npub fn operation_for(req: &HttpRequest) -> Option<&str> {{ {RT}::operation(&SERVICE_INFO, req).ok() }}"
        );
    }
}
