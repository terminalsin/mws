//! awsQuery server generation: request decoding with validation, XML
//! response encoding, the handler trait and the dispatcher.

use std::collections::BTreeSet;
use std::fmt::Write;

use mws_smithy::{Model, Shape, ShapeType};
use serde_json::Value;

use crate::common::{self, de_fn_name, qualified_type, ser_fn_name, Constraints};
use crate::naming::{lower_camel, rust_str, snake_case, type_name};
use crate::rust_types::{field_name, presence, Presence, TypeGen};
use crate::xml_ser::XmlSer;

pub fn generate(model: &Model) -> String {
    Gen::new(model).run()
}

struct Gen<'m> {
    model: &'m Model,
    types: TypeGen<'m>,
    out: String,
    constraints: Constraints,
}

impl<'m> Gen<'m> {
    fn new(model: &'m Model) -> Self {
        Self { model, types: TypeGen::new(model), out: String::new(), constraints: Constraints::default() }
    }

    fn run(mut self) -> String {
        let model = self.model;
        let service = model.service().expect("model has a service");
        assert!(service.has_trait("aws.protocols#awsQuery"), "{} does not use the awsQuery protocol", service.id);
        let ops = model.operations(service);
        let namespace = service
            .get_trait("xmlNamespace")
            .and_then(|v| v.get("uri"))
            .and_then(Value::as_str)
            .expect("awsQuery services declare an xmlNamespace");
        let version = service.version.clone().unwrap_or_default();

        let inputs: Vec<String> = ops.iter().filter_map(|o| o.input.clone()).collect();
        let outputs: Vec<String> = ops.iter().filter_map(|o| o.output.clone()).collect();
        let input_closure = self.types.closure(inputs);
        let output_closure = self.types.closure(outputs);
        let all: BTreeSet<String> = input_closure.union(&output_closure).cloned().collect();

        let errors = common::all_errors(service, &ops);

        let w = &mut self.out;
        let _ = writeln!(w, "// @generated by mws-codegen from {}. Do not edit.", service.id);
        let _ = writeln!(w, "use ::mws_proto_query::__private::{{async_trait, chrono}};");
        let _ = writeln!(w, "use ::mws_proto_query::{{Decoder, Params, ServiceInfo, XmlWriter}};");
        let _ = writeln!(w, "use ::mws_core::{{HttpResponse, RequestContext, ServiceError}};");
        let _ = writeln!(w);
        let _ = writeln!(
            w,
            "pub const SERVICE_INFO: ServiceInfo = ServiceInfo {{ xml_namespace: {}, version: {} }};",
            rust_str(namespace),
            rust_str(&version)
        );
        let _ = writeln!(
            w,
            "/// Every operation in the model, by wire name.\npub const OPERATIONS: &[&str] = &[{}];",
            ops.iter().map(|o| rust_str(o.name())).collect::<Vec<_>>().join(", ")
        );

        // ---- types ----
        let _ = writeln!(w, "\npub mod types {{\n    use super::chrono;");
        let mut types_src = String::new();
        self.types.emit_types(&all, &mut types_src);
        self.out.push_str(&types_src);
        let _ = writeln!(self.out, "}}");

        // ---- errors ----
        common::emit_errors(model, &errors, true, &mut self.out);

        // ---- handler ----
        common::emit_handler(model, &ops, &mut self.out);

        // ---- dispatch ----
        self.emit_dispatch(&ops);

        // ---- decoders ----
        let mut de = String::new();
        for id in &input_closure {
            let s = model.expect(id);
            match s.ty {
                ShapeType::Structure | ShapeType::Union => self.emit_de_aggregate(s, &mut de),
                ShapeType::List | ShapeType::Set => self.emit_de_list(s, &mut de),
                ShapeType::Map => self.emit_de_map(s, &mut de),
                _ => {}
            }
        }
        let _ = writeln!(self.out, "\n#[allow(unused_variables, unused_mut, clippy::all)]\nmod de {{");
        let _ = writeln!(self.out, "    use super::*;");
        self.constraints.emit_statics("::mws_proto_query", &mut self.out);
        self.out.push_str(&de);
        let _ = writeln!(self.out, "}}");

        // ---- serializers ----
        let mut ser = String::new();
        XmlSer { model, types: &self.types }.emit_all(&output_closure, &mut ser);
        let _ = writeln!(self.out, "\n#[allow(unused_variables, clippy::all)]\nmod ser {{\n    use super::*;");
        self.out.push_str(&ser);
        let _ = writeln!(self.out, "}}");

        // ---- JSON entry point (scenarios) ----
        crate::json_codec::emit_invoke(model, &ops, "json_de", "json_ser", "ValidationError", &mut self.out);
        let mut codec = crate::json_codec::JsonCodec::new(model, &self.types);
        let de = codec.de_module(&input_closure, "json_de");
        let ser = codec.ser_module(&output_closure, "json_ser");
        self.out.push_str(&de);
        self.out.push_str(&ser);
        self.out
    }

    // ------------------------------------------------------------------------

    fn emit_dispatch(&mut self, ops: &[&Shape]) {
        let mut w = String::new();
        let _ = writeln!(
            w,
            "\n/// Decode `params`, run the matching handler method, and encode the result.\npub async fn dispatch<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, params: &Params) -> HttpResponse {{"
        );
        let _ = writeln!(w, "    let rid = ctx.request_id.as_str();");
        let _ = writeln!(w, "    let result: Result<String, ServiceError> = match params.get(\"Action\") {{");
        let _ = writeln!(w, "        None => Err(ServiceError::missing_action()),");
        for op in ops {
            let name = op.name();
            let method = crate::naming::ident(&snake_case(name));
            let _ = writeln!(w, "        Some({}) => {{", rust_str(name));
            match &op.input {
                Some(i) => {
                    let de_fn = de_fn_name(self.model.expect(i));
                    let _ = writeln!(w, "            let mut d = Decoder::new(params);");
                    let _ = writeln!(
                        w,
                        "            let input = de::{de_fn}(&mut d, \"\", \"\", false).unwrap_or_default();"
                    );
                    let _ = writeln!(w, "            match d.finish() {{");
                    let _ = writeln!(w, "                Err(e) => Err(e),");
                    let _ = writeln!(w, "                Ok(()) => handler.{method}(ctx, input).await,");
                    let _ = writeln!(w, "            }}");
                }
                None => {
                    let _ = writeln!(w, "            handler.{method}(ctx, ()).await");
                }
            }
            match &op.output {
                Some(o) => {
                    let ser_fn = ser_fn_name(self.model.expect(o));
                    let _ = writeln!(
                        w,
                        "            .map(|out| ::mws_proto_query::success_body(&SERVICE_INFO, {}, rid, Some(&|w: &mut XmlWriter| ser::{ser_fn}(w, &out))))",
                        rust_str(name)
                    );
                }
                None => {
                    let _ = writeln!(
                        w,
                        "            .map(|()| ::mws_proto_query::success_body(&SERVICE_INFO, {}, rid, None))",
                        rust_str(name)
                    );
                }
            }
            let _ = writeln!(w, "        }}");
        }
        let _ = writeln!(w, "        Some(other) => Err(ServiceError::invalid_action(other)),");
        let _ = writeln!(w, "    }};");
        let _ = writeln!(w, "    match result {{");
        let _ = writeln!(w, "        Ok(body) => ::mws_proto_query::xml_response(200, rid, body),");
        let _ = writeln!(w, "        Err(e) => ::mws_proto_query::error_response(&SERVICE_INFO, rid, &e),");
        let _ = writeln!(w, "    }}\n}}");
        self.out.push_str(&w);
    }

    // ---- decoding ----------------------------------------------------------

    /// Expression of type `Option<T>` decoding `target` from key var `k` and
    /// path var `p`. `flat` is the member's `@xmlFlattened`.
    fn de_expr(&self, target: &str, flat: bool) -> String {
        let s = self.model.expect(target);
        match s.ty {
            ShapeType::String
            | ShapeType::Enum
            | ShapeType::BigInteger
            | ShapeType::BigDecimal
            | ShapeType::Document => "d.string(&k)".into(),
            ShapeType::Boolean => "d.boolean(&k, &p)".into(),
            ShapeType::Byte => "d.number::<i8>(&k, &p)".into(),
            ShapeType::Short => "d.number::<i16>(&k, &p)".into(),
            ShapeType::Integer | ShapeType::IntEnum => "d.number::<i32>(&k, &p)".into(),
            ShapeType::Long => "d.number::<i64>(&k, &p)".into(),
            ShapeType::Float => "d.number::<f32>(&k, &p)".into(),
            ShapeType::Double => "d.number::<f64>(&k, &p)".into(),
            ShapeType::Timestamp => "d.timestamp(&k, &p)".into(),
            ShapeType::Blob => "d.blob(&k, &p)".into(),
            _ => format!("{}(d, &k, &p, {flat})", de_fn_name(s)),
        }
    }

    fn emit_de_aggregate(&mut self, s: &Shape, w: &mut String) {
        let ty = type_name(s.name());
        let is_union = s.ty == ShapeType::Union;
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str, path: &str, _flat: bool) -> Option<types::{ty}> {{",
            de_fn_name(s)
        );
        let _ = writeln!(w, "        if !key.is_empty() && !d.has_prefix(key) {{ return None; }}");
        if is_union {
            let _ = writeln!(w, "        let mut out: Option<types::{ty}> = None;");
        } else {
            let _ = writeln!(w, "        let mut out = types::{ty}::default();");
        }
        for m in &s.members {
            let target = self.model.expect(&m.target).clone();
            let wire = m.get_trait("xmlName").and_then(Value::as_str).unwrap_or(&m.name).to_string();
            let flat = m.has_trait("xmlFlattened");
            let _ = writeln!(w, "        {{");
            let _ = writeln!(
                w,
                "            let k = if key.is_empty() {{ {}.to_string() }} else {{ format!(\"{{key}}.{wire}\") }};",
                rust_str(&wire)
            );
            let camel = lower_camel(&m.name);
            let _ = writeln!(
                w,
                "            let p = if path.is_empty() {{ {}.to_string() }} else {{ format!(\"{{path}}.{camel}\") }};",
                rust_str(&camel)
            );
            let _ = writeln!(w, "            let val = {};", self.de_expr(&m.target, flat));
            let checks = self.constraints.checks(Some(m), &target);
            if !checks.is_empty() {
                let _ = writeln!(w, "            if let Some(v) = &val {{ {checks} }}");
            }
            let boxed = self.types.is_boxed(&s.id, &m.target);
            let wrap = |e: &str| if boxed { format!("::std::boxed::Box::new({e})") } else { e.to_string() };
            let field = field_name(m);
            if is_union {
                let _ = writeln!(
                    w,
                    "            if out.is_none() {{ if let Some(v) = val {{ out = Some(types::{ty}::{}({})); }} }}",
                    type_name(&m.name),
                    wrap("v")
                );
            } else {
                match presence(m) {
                    Presence::Required => {
                        let _ = writeln!(w, "            d.required(&val, &p);");
                        let _ = writeln!(w, "            if let Some(v) = val {{ out.{field} = {}; }}", wrap("v"));
                    }
                    Presence::Defaulted => {
                        let _ = writeln!(w, "            if let Some(v) = val {{ out.{field} = {}; }}", wrap("v"));
                    }
                    Presence::Optional => {
                        let _ = writeln!(w, "            out.{field} = val.map(|v| {});", wrap("v"));
                    }
                }
            }
            let _ = writeln!(w, "        }}");
        }
        if is_union {
            let _ = writeln!(w, "        out");
        } else {
            let _ = writeln!(w, "        Some(out)");
        }
        let _ = writeln!(w, "    }}");
    }

    fn emit_de_list(&mut self, s: &Shape, w: &mut String) {
        let member = s.member.clone().unwrap();
        let target = self.model.expect(&member.target).clone();
        let item_name = member.get_trait("xmlName").and_then(Value::as_str).unwrap_or("member").to_string();
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str, path: &str, flat: bool) -> Option<{}> {{",
            de_fn_name(s),
            qualified_type(self.model, &s.id)
        );
        let _ = writeln!(w, "        if d.is_explicitly_empty(key) {{ return Some(Vec::new()); }}");
        let _ = writeln!(
            w,
            "        let prefix = if flat {{ key.to_string() }} else {{ format!(\"{{key}}.{item_name}\") }};"
        );
        let _ = writeln!(w, "        let idx = d.indexes(&prefix);");
        let _ = writeln!(w, "        if idx.is_empty() {{ return None; }}");
        let _ = writeln!(w, "        let mut out = Vec::with_capacity(idx.len());");
        let _ = writeln!(w, "        for i in idx {{");
        let _ = writeln!(w, "            let k = format!(\"{{prefix}}.{{i}}\");");
        let _ = writeln!(w, "            let p = format!(\"{{path}}.{{i}}.member\");");
        let _ = writeln!(w, "            let val = {};", self.de_expr(&member.target, false));
        let checks = self.constraints.checks(Some(&member), &target);
        let _ = writeln!(w, "            if let Some(v) = val {{ {{ let v = &v; {checks} }} out.push(v); }}");
        let _ = writeln!(w, "        }}");
        let _ = writeln!(w, "        Some(out)");
        let _ = writeln!(w, "    }}");
    }

    fn emit_de_map(&mut self, s: &Shape, w: &mut String) {
        let key_m = s.key.clone().unwrap();
        let val_m = s.value.clone().unwrap();
        let key_name = key_m.get_trait("xmlName").and_then(Value::as_str).unwrap_or("key").to_string();
        let val_name = val_m.get_trait("xmlName").and_then(Value::as_str).unwrap_or("value").to_string();
        let key_target = self.model.expect(&key_m.target).clone();
        let val_target = self.model.expect(&val_m.target).clone();
        let value_ty = qualified_type(self.model, &val_m.target);
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str, path: &str, flat: bool) -> Option<::std::collections::BTreeMap<String, {value_ty}>> {{",
            de_fn_name(s)
        );
        let _ = writeln!(w, "        if d.is_explicitly_empty(key) {{ return Some(Default::default()); }}");
        let _ =
            writeln!(w, "        let prefix = if flat {{ key.to_string() }} else {{ format!(\"{{key}}.entry\") }};");
        let _ = writeln!(w, "        let idx = d.indexes(&prefix);");
        let _ = writeln!(w, "        if idx.is_empty() {{ return None; }}");
        let _ = writeln!(w, "        let mut out = ::std::collections::BTreeMap::new();");
        let _ = writeln!(w, "        for i in idx {{");
        let _ = writeln!(w, "            let k = format!(\"{{prefix}}.{{i}}.{key_name}\");");
        let _ = writeln!(w, "            let p = format!(\"{{path}}.{{i}}.key\");");
        let _ = writeln!(w, "            let map_key = d.string(&k);");
        let kc = self.constraints.checks(Some(&key_m), &key_target);
        let _ = writeln!(w, "            if let Some(v) = &map_key {{ {kc} }}");
        let _ = writeln!(w, "            let k = format!(\"{{prefix}}.{{i}}.{val_name}\");");
        let _ = writeln!(w, "            let p = format!(\"{{path}}.{{i}}.value\");");
        let _ = writeln!(w, "            let val = {};", self.de_expr(&val_m.target, false));
        let vc = self.constraints.checks(Some(&val_m), &val_target);
        let _ = writeln!(w, "            if let Some(v) = &val {{ {vc} }}");
        let _ = writeln!(w, "            if let (Some(mk), Some(v)) = (map_key, val) {{ out.insert(mk, v); }}");
        let _ = writeln!(w, "        }}");
        let _ = writeln!(w, "        Some(out)");
        let _ = writeln!(w, "    }}");
    }
}
