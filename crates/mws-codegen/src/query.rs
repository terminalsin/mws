//! awsQuery server generation: request decoding with validation, XML
//! response encoding, the handler trait and the dispatcher.

use std::collections::BTreeSet;
use std::fmt::Write;

use mws_smithy::{Bounds, Member, Model, Shape, ShapeType};
use serde_json::Value;

use crate::naming::{lower_camel, rust_str, snake_case, type_name};
use crate::regex_compat;
use crate::rust_types::{enum_const_name, field_name, presence, Presence, TypeGen};

pub fn generate(model: &Model) -> String {
    Gen::new(model).run()
}

struct Gen<'m> {
    model: &'m Model,
    types: TypeGen<'m>,
    out: String,
    regexes: Vec<String>,
}

impl<'m> Gen<'m> {
    fn new(model: &'m Model) -> Self {
        Self { model, types: TypeGen::new(model), out: String::new(), regexes: Vec::new() }
    }

    fn run(mut self) -> String {
        let model = self.model;
        let service = model.service().expect("model has a service");
        assert!(service.has_trait("aws.protocols#awsQuery"), "{} does not use the awsQuery protocol", service.id);
        let ops = model.operations(service);
        let namespace = service
            .get_trait("xmlNamespace")
            .and_then(|v| v.get("uri"))
            .and_then(Value::as_str)
            .expect("awsQuery services declare an xmlNamespace");
        let version = service.version.clone().unwrap_or_default();

        let inputs: Vec<String> = ops.iter().filter_map(|o| o.input.clone()).collect();
        let outputs: Vec<String> = ops.iter().filter_map(|o| o.output.clone()).collect();
        let input_closure = self.types.closure(inputs);
        let output_closure = self.types.closure(outputs);
        let all: BTreeSet<String> = input_closure.union(&output_closure).cloned().collect();

        let mut errors: BTreeSet<String> = service.errors.iter().cloned().collect();
        for o in &ops {
            errors.extend(o.errors.iter().cloned());
        }

        let w = &mut self.out;
        let _ = writeln!(w, "// @generated by mws-codegen from {}. Do not edit.", service.id);
        let _ = writeln!(w, "use ::mws_proto_query::__private::{{async_trait, chrono}};");
        let _ = writeln!(w, "use ::mws_proto_query::{{Decoder, Params, ServiceInfo, XmlWriter}};");
        let _ = writeln!(w, "use ::mws_core::{{HttpResponse, RequestContext, ServiceError}};");
        let _ = writeln!(w);
        let _ = writeln!(
            w,
            "pub const SERVICE_INFO: ServiceInfo = ServiceInfo {{ xml_namespace: {}, version: {} }};",
            rust_str(namespace),
            rust_str(&version)
        );
        let _ = writeln!(
            w,
            "/// Every operation in the model, by wire name.\npub const OPERATIONS: &[&str] = &[{}];",
            ops.iter().map(|o| rust_str(o.name())).collect::<Vec<_>>().join(", ")
        );

        // ---- types ----
        let _ = writeln!(w, "\npub mod types {{\n    use super::chrono;");
        let mut types_src = String::new();
        self.types.emit_types(&all, &mut types_src);
        self.out.push_str(&types_src);
        let _ = writeln!(self.out, "}}");

        // ---- errors ----
        self.emit_errors(&errors);

        // ---- handler ----
        self.emit_handler(&ops);

        // ---- dispatch ----
        self.emit_dispatch(&ops);

        // ---- decoders ----
        let mut de = String::new();
        for id in &input_closure {
            let s = model.expect(id);
            match s.ty {
                ShapeType::Structure | ShapeType::Union => self.emit_de_aggregate(s, &mut de),
                ShapeType::List | ShapeType::Set => self.emit_de_list(s, &mut de),
                ShapeType::Map => self.emit_de_map(s, &mut de),
                _ => {}
            }
        }
        let _ = writeln!(self.out, "\n#[allow(unused_variables, unused_mut, clippy::all)]\nmod de {{");
        let _ = writeln!(self.out, "    use super::*;");
        for (i, pat) in self.regexes.iter().enumerate() {
            let _ = writeln!(
                self.out,
                "    static RE_{i}: ::std::sync::LazyLock<::mws_proto_query::__private::regex::Regex> = ::std::sync::LazyLock::new(|| ::mws_proto_query::__private::regex::Regex::new({}).unwrap());",
                rust_str(pat)
            );
        }
        self.out.push_str(&de);
        let _ = writeln!(self.out, "}}");

        // ---- serializers ----
        let mut ser = String::new();
        for id in &output_closure {
            let s = model.expect(id);
            match s.ty {
                ShapeType::Structure => self.emit_ser_struct(s, &mut ser),
                ShapeType::Union => self.emit_ser_union(s, &mut ser),
                ShapeType::List | ShapeType::Set => self.emit_ser_list(s, &mut ser),
                ShapeType::Map => self.emit_ser_map(s, &mut ser),
                _ => {}
            }
        }
        let _ = writeln!(self.out, "\n#[allow(unused_variables, clippy::all)]\nmod ser {{\n    use super::*;");
        self.out.push_str(&ser);
        let _ = writeln!(self.out, "}}");
        self.out
    }

    // ------------------------------------------------------------------------

    fn emit_errors(&mut self, errors: &BTreeSet<String>) {
        let w = &mut self.out;
        let _ = writeln!(w, "\n/// Constructors for every error the model declares.\npub mod errors {{");
        let _ = writeln!(w, "    use ::mws_core::{{ErrorFault, ServiceError}};");
        for id in errors {
            let s = self.model.expect(id);
            let (code, status) = error_code_and_status(s);
            let fault =
                if s.get_trait("error").and_then(Value::as_str) == Some("server") { "Server" } else { "Client" };
            let fn_name = snake_case(s.name().strip_suffix("Exception").unwrap_or(s.name()));
            let _ = writeln!(w, "    /// `{code}` (HTTP {status}), from `{id}`.");
            let _ = writeln!(w, "    pub const {}: &str = {};", fn_name.to_ascii_uppercase(), rust_str(&code));
            let _ = writeln!(
                w,
                "    pub fn {fn_name}(message: impl Into<String>) -> ServiceError {{ ServiceError::new({}, {status}, ErrorFault::{fault}, message) }}",
                rust_str(&code)
            );
        }
        let _ = writeln!(w, "}}");
    }

    fn io_types(&self, op: &Shape) -> (String, String) {
        let input = op.input.as_ref().map(|i| format!("types::{}", type_name(self.model.expect(i).name())));
        let output = op.output.as_ref().map(|o| format!("types::{}", type_name(self.model.expect(o).name())));
        (input.unwrap_or_else(|| "()".into()), output.unwrap_or_else(|| "()".into()))
    }

    fn emit_handler(&mut self, ops: &[&Shape]) {
        let mut w = String::new();
        let _ = writeln!(w, "\n/// Implement the operations you support; the rest answer `NotImplemented`.");
        let _ = writeln!(w, "#[async_trait::async_trait]\npub trait Handler: Send + Sync {{");
        for op in ops {
            let (input, output) = self.io_types(op);
            let _ = writeln!(
                w,
                "    async fn {}(&self, ctx: &RequestContext, input: {input}) -> Result<{output}, ServiceError> {{\n        let _ = (ctx, input);\n        Err(ServiceError::not_implemented({}))\n    }}",
                crate::naming::ident(&snake_case(op.name())),
                rust_str(op.name())
            );
        }
        let _ = writeln!(w, "}}");
        self.out.push_str(&w);
    }

    fn emit_dispatch(&mut self, ops: &[&Shape]) {
        let mut w = String::new();
        let _ = writeln!(
            w,
            "\n/// Decode `params`, run the matching handler method, and encode the result.\npub async fn dispatch<H: Handler + ?Sized>(handler: &H, ctx: &RequestContext, params: &Params) -> HttpResponse {{"
        );
        let _ = writeln!(w, "    let rid = ctx.request_id.as_str();");
        let _ = writeln!(w, "    let result: Result<String, ServiceError> = match params.get(\"Action\") {{");
        let _ = writeln!(w, "        None => Err(ServiceError::missing_action()),");
        for op in ops {
            let name = op.name();
            let method = crate::naming::ident(&snake_case(name));
            let _ = writeln!(w, "        Some({}) => {{", rust_str(name));
            match &op.input {
                Some(i) => {
                    let de_fn = de_fn_name(self.model.expect(i));
                    let _ = writeln!(w, "            let mut d = Decoder::new(params);");
                    let _ = writeln!(
                        w,
                        "            let input = de::{de_fn}(&mut d, \"\", \"\", false).unwrap_or_default();"
                    );
                    let _ = writeln!(w, "            match d.finish() {{");
                    let _ = writeln!(w, "                Err(e) => Err(e),");
                    let _ = writeln!(w, "                Ok(()) => handler.{method}(ctx, input).await,");
                    let _ = writeln!(w, "            }}");
                }
                None => {
                    let _ = writeln!(w, "            handler.{method}(ctx, ()).await");
                }
            }
            match &op.output {
                Some(o) => {
                    let ser_fn = ser_fn_name(self.model.expect(o));
                    let _ = writeln!(
                        w,
                        "            .map(|out| ::mws_proto_query::success_body(&SERVICE_INFO, {}, rid, Some(&|w: &mut XmlWriter| ser::{ser_fn}(w, &out))))",
                        rust_str(name)
                    );
                }
                None => {
                    let _ = writeln!(
                        w,
                        "            .map(|()| ::mws_proto_query::success_body(&SERVICE_INFO, {}, rid, None))",
                        rust_str(name)
                    );
                }
            }
            let _ = writeln!(w, "        }}");
        }
        let _ = writeln!(w, "        Some(other) => Err(ServiceError::invalid_action(other)),");
        let _ = writeln!(w, "    }};");
        let _ = writeln!(w, "    match result {{");
        let _ = writeln!(w, "        Ok(body) => ::mws_proto_query::xml_response(200, rid, body),");
        let _ = writeln!(w, "        Err(e) => ::mws_proto_query::error_response(&SERVICE_INFO, rid, &e),");
        let _ = writeln!(w, "    }}\n}}");
        self.out.push_str(&w);
    }

    // ---- decoding ----------------------------------------------------------

    /// Expression of type `Option<T>` decoding `target` from key var `k` and
    /// path var `p`. `flat` is the member's `@xmlFlattened`.
    fn de_expr(&self, target: &str, flat: bool) -> String {
        let s = self.model.expect(target);
        match s.ty {
            ShapeType::String
            | ShapeType::Enum
            | ShapeType::BigInteger
            | ShapeType::BigDecimal
            | ShapeType::Document => "d.string(&k)".into(),
            ShapeType::Boolean => "d.boolean(&k, &p)".into(),
            ShapeType::Byte => "d.number::<i8>(&k, &p)".into(),
            ShapeType::Short => "d.number::<i16>(&k, &p)".into(),
            ShapeType::Integer | ShapeType::IntEnum => "d.number::<i32>(&k, &p)".into(),
            ShapeType::Long => "d.number::<i64>(&k, &p)".into(),
            ShapeType::Float => "d.number::<f32>(&k, &p)".into(),
            ShapeType::Double => "d.number::<f64>(&k, &p)".into(),
            ShapeType::Timestamp => "d.timestamp(&k, &p)".into(),
            ShapeType::Blob => "d.blob(&k, &p)".into(),
            _ => format!("{}(d, &k, &p, {flat})", de_fn_name(s)),
        }
    }

    /// Validation statements for value var `v` (a `&T`) at path var `p`.
    fn constraints(&mut self, member: Option<&Member>, target: &Shape) -> String {
        let pick = |name: &str| member.and_then(|m| m.get_trait(name)).or_else(|| target.get_trait(name)).cloned();
        let mut out = String::new();
        let is_string = matches!(target.ty, ShapeType::String | ShapeType::Enum);
        if let Some(b) = Bounds::from_trait(pick("length").as_ref()) {
            let (len, shown) = match target.ty {
                ShapeType::String | ShapeType::Enum => ("v.chars().count()", "v.as_str()".to_string()),
                ShapeType::List | ShapeType::Set => ("v.len()", "&::mws_proto_query::render_list(v)".to_string()),
                _ => ("v.len()", "\"\"".to_string()),
            };
            let _ = writeln!(out, "d.check_length(&p, {shown}, {len}, {}, {});", opt_u64(b.min), opt_u64(b.max));
        }
        if is_string {
            if let Some(Value::String(pat)) = pick("pattern") {
                if let Some(translated) = regex_compat::translate(&pat) {
                    let idx = match self.regexes.iter().position(|r| *r == translated) {
                        Some(i) => i,
                        None => {
                            self.regexes.push(translated);
                            self.regexes.len() - 1
                        }
                    };
                    let _ = writeln!(out, "d.check_pattern(&p, v, &RE_{idx}, {});", rust_str(&pat));
                } else {
                    let _ =
                        writeln!(out, "// pattern {} is not expressible with the regex crate; skipped", rust_str(&pat));
                }
            }
        }
        if let Some(b) = Bounds::from_trait(pick("range").as_ref()) {
            if !matches!(target.ty, ShapeType::String) {
                let _ = writeln!(out, "d.check_range(&p, *v as f64, {}, {});", opt_f64(b.min), opt_f64(b.max));
            }
        }
        if target.ty == ShapeType::Enum {
            let _ = writeln!(out, "d.check_enum(&p, v, types::{});", enum_const_name(target));
        }
        out
    }

    fn emit_de_aggregate(&mut self, s: &Shape, w: &mut String) {
        let ty = type_name(s.name());
        let is_union = s.ty == ShapeType::Union;
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str, path: &str, _flat: bool) -> Option<types::{ty}> {{",
            de_fn_name(s)
        );
        let _ = writeln!(w, "        if !key.is_empty() && !d.has_prefix(key) {{ return None; }}");
        if is_union {
            let _ = writeln!(w, "        let mut out: Option<types::{ty}> = None;");
        } else {
            let _ = writeln!(w, "        let mut out = types::{ty}::default();");
        }
        for m in &s.members {
            let target = self.model.expect(&m.target).clone();
            let wire = m.get_trait("xmlName").and_then(Value::as_str).unwrap_or(&m.name).to_string();
            let flat = m.has_trait("xmlFlattened");
            let _ = writeln!(w, "        {{");
            let _ = writeln!(
                w,
                "            let k = if key.is_empty() {{ {}.to_string() }} else {{ format!(\"{{key}}.{wire}\") }};",
                rust_str(&wire)
            );
            let camel = lower_camel(&m.name);
            let _ = writeln!(
                w,
                "            let p = if path.is_empty() {{ {}.to_string() }} else {{ format!(\"{{path}}.{camel}\") }};",
                rust_str(&camel)
            );
            let _ = writeln!(w, "            let val = {};", self.de_expr(&m.target, flat));
            let checks = self.constraints(Some(m), &target);
            if !checks.is_empty() {
                let _ = writeln!(w, "            if let Some(v) = &val {{ {checks} }}");
            }
            let boxed = self.types.is_boxed(&s.id, &m.target);
            let wrap = |e: &str| if boxed { format!("::std::boxed::Box::new({e})") } else { e.to_string() };
            let field = field_name(m);
            if is_union {
                let _ = writeln!(
                    w,
                    "            if out.is_none() {{ if let Some(v) = val {{ out = Some(types::{ty}::{}({})); }} }}",
                    type_name(&m.name),
                    wrap("v")
                );
            } else {
                match presence(m) {
                    Presence::Required => {
                        let _ = writeln!(w, "            d.required(&val, &p);");
                        let _ = writeln!(w, "            if let Some(v) = val {{ out.{field} = {}; }}", wrap("v"));
                    }
                    Presence::Defaulted => {
                        let _ = writeln!(w, "            if let Some(v) = val {{ out.{field} = {}; }}", wrap("v"));
                    }
                    Presence::Optional => {
                        let _ = writeln!(w, "            out.{field} = val.map(|v| {});", wrap("v"));
                    }
                }
            }
            let _ = writeln!(w, "        }}");
        }
        if is_union {
            let _ = writeln!(w, "        out");
        } else {
            let _ = writeln!(w, "        Some(out)");
        }
        let _ = writeln!(w, "    }}");
    }

    fn emit_de_list(&mut self, s: &Shape, w: &mut String) {
        let member = s.member.clone().unwrap();
        let target = self.model.expect(&member.target).clone();
        let item_name = member.get_trait("xmlName").and_then(Value::as_str).unwrap_or("member").to_string();
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str, path: &str, flat: bool) -> Option<{}> {{",
            de_fn_name(s),
            qualified_type(self.model, &s.id)
        );
        let _ = writeln!(w, "        if d.is_explicitly_empty(key) {{ return Some(Vec::new()); }}");
        let _ = writeln!(
            w,
            "        let prefix = if flat {{ key.to_string() }} else {{ format!(\"{{key}}.{item_name}\") }};"
        );
        let _ = writeln!(w, "        let idx = d.indexes(&prefix);");
        let _ = writeln!(w, "        if idx.is_empty() {{ return None; }}");
        let _ = writeln!(w, "        let mut out = Vec::with_capacity(idx.len());");
        let _ = writeln!(w, "        for i in idx {{");
        let _ = writeln!(w, "            let k = format!(\"{{prefix}}.{{i}}\");");
        let _ = writeln!(w, "            let p = format!(\"{{path}}.{{i}}.member\");");
        let _ = writeln!(w, "            let val = {};", self.de_expr(&member.target, false));
        let checks = self.constraints(Some(&member), &target);
        let _ = writeln!(w, "            if let Some(v) = val {{ {{ let v = &v; {checks} }} out.push(v); }}");
        let _ = writeln!(w, "        }}");
        let _ = writeln!(w, "        Some(out)");
        let _ = writeln!(w, "    }}");
    }

    fn emit_de_map(&mut self, s: &Shape, w: &mut String) {
        let key_m = s.key.clone().unwrap();
        let val_m = s.value.clone().unwrap();
        let key_name = key_m.get_trait("xmlName").and_then(Value::as_str).unwrap_or("key").to_string();
        let val_name = val_m.get_trait("xmlName").and_then(Value::as_str).unwrap_or("value").to_string();
        let key_target = self.model.expect(&key_m.target).clone();
        let val_target = self.model.expect(&val_m.target).clone();
        let value_ty = qualified_type(self.model, &val_m.target);
        let _ = writeln!(
            w,
            "    pub(super) fn {}(d: &mut Decoder<'_>, key: &str, path: &str, flat: bool) -> Option<::std::collections::BTreeMap<String, {value_ty}>> {{",
            de_fn_name(s)
        );
        let _ = writeln!(w, "        if d.is_explicitly_empty(key) {{ return Some(Default::default()); }}");
        let _ =
            writeln!(w, "        let prefix = if flat {{ key.to_string() }} else {{ format!(\"{{key}}.entry\") }};");
        let _ = writeln!(w, "        let idx = d.indexes(&prefix);");
        let _ = writeln!(w, "        if idx.is_empty() {{ return None; }}");
        let _ = writeln!(w, "        let mut out = ::std::collections::BTreeMap::new();");
        let _ = writeln!(w, "        for i in idx {{");
        let _ = writeln!(w, "            let k = format!(\"{{prefix}}.{{i}}.{key_name}\");");
        let _ = writeln!(w, "            let p = format!(\"{{path}}.{{i}}.key\");");
        let _ = writeln!(w, "            let map_key = d.string(&k);");
        let kc = self.constraints(Some(&key_m), &key_target);
        let _ = writeln!(w, "            if let Some(v) = &map_key {{ {kc} }}");
        let _ = writeln!(w, "            let k = format!(\"{{prefix}}.{{i}}.{val_name}\");");
        let _ = writeln!(w, "            let p = format!(\"{{path}}.{{i}}.value\");");
        let _ = writeln!(w, "            let val = {};", self.de_expr(&val_m.target, false));
        let vc = self.constraints(Some(&val_m), &val_target);
        let _ = writeln!(w, "            if let Some(v) = &val {{ {vc} }}");
        let _ = writeln!(w, "            if let (Some(mk), Some(v)) = (map_key, val) {{ out.insert(mk, v); }}");
        let _ = writeln!(w, "        }}");
        let _ = writeln!(w, "        Some(out)");
        let _ = writeln!(w, "    }}");
    }

    // ---- serialization -----------------------------------------------------

    /// Statements writing value expr `v` (a reference) as element `name`.
    fn ser_value(&self, target: &str, v: &str, name: &str, flat: bool) -> String {
        let s = self.model.expect(target);
        match s.ty {
            ShapeType::String
            | ShapeType::Enum
            | ShapeType::BigInteger
            | ShapeType::BigDecimal
            | ShapeType::Document => {
                format!("w.leaf({name}, {v});")
            }
            ShapeType::Boolean => format!("w.leaf_bool({name}, *{v});"),
            ShapeType::Byte
            | ShapeType::Short
            | ShapeType::Integer
            | ShapeType::IntEnum
            | ShapeType::Long
            | ShapeType::Float
            | ShapeType::Double => format!("w.leaf_num({name}, {v});"),
            ShapeType::Timestamp => format!("w.leaf_timestamp({name}, {v});"),
            ShapeType::Blob => format!("w.leaf_blob({name}, {v});"),
            ShapeType::Structure | ShapeType::Union => {
                format!("w.open({name}); {}(w, {v}); w.close({name});", ser_fn_name(s))
            }
            ShapeType::List | ShapeType::Set | ShapeType::Map => format!("{}(w, {name}, {v}, {flat});", ser_fn_name(s)),
            _ => String::new(),
        }
    }

    fn emit_ser_struct(&mut self, s: &Shape, w: &mut String) {
        let ty = type_name(s.name());
        let _ = writeln!(w, "    pub(super) fn {}(w: &mut XmlWriter, v: &types::{ty}) {{", ser_fn_name(s));
        for m in &s.members {
            let wire = m.get_trait("xmlName").and_then(Value::as_str).unwrap_or(&m.name);
            let flat = m.has_trait("xmlFlattened");
            let field = field_name(m);
            let boxed = self.types.is_boxed(&s.id, &m.target);
            let deref = if boxed { "&**" } else { "" };
            match presence(m) {
                Presence::Optional => {
                    let stmt = self.ser_value(&m.target, &format!("{deref}x"), &rust_str(wire), flat);
                    let _ = writeln!(w, "        if let Some(x) = &v.{field} {{ {stmt} }}");
                }
                _ => {
                    let stmt = self.ser_value(
                        &m.target,
                        &format!("{}&v.{field}", if boxed { "&*" } else { "" }),
                        &rust_str(wire),
                        flat,
                    );
                    let _ = writeln!(w, "        {stmt}");
                }
            }
        }
        let _ = writeln!(w, "    }}");
    }

    fn emit_ser_union(&mut self, s: &Shape, w: &mut String) {
        let ty = type_name(s.name());
        let _ = writeln!(w, "    pub(super) fn {}(w: &mut XmlWriter, v: &types::{ty}) {{", ser_fn_name(s));
        let _ = writeln!(w, "        match v {{");
        for m in &s.members {
            let wire = m.get_trait("xmlName").and_then(Value::as_str).unwrap_or(&m.name);
            let deref = if self.types.is_boxed(&s.id, &m.target) { "&**" } else { "" };
            let stmt = self.ser_value(&m.target, &format!("{deref}x"), &rust_str(wire), m.has_trait("xmlFlattened"));
            let _ = writeln!(w, "            types::{ty}::{}(x) => {{ {stmt} }}", type_name(&m.name));
        }
        let _ = writeln!(w, "        }}\n    }}");
    }

    fn emit_ser_list(&mut self, s: &Shape, w: &mut String) {
        let member = s.member.as_ref().unwrap();
        let item_name = member.get_trait("xmlName").and_then(Value::as_str).unwrap_or("member");
        let elem_ty = qualified_type(self.model, &member.target);
        let item_stmt = self.ser_value(&member.target, "x", &rust_str(item_name), false);
        let flat_stmt = self.ser_value(&member.target, "x", "name", false);
        let _ = writeln!(
            w,
            "    pub(super) fn {}(w: &mut XmlWriter, name: &str, v: &[{elem_ty}], flat: bool) {{",
            ser_fn_name(s)
        );
        let _ = writeln!(w, "        if flat {{ for x in v {{ {flat_stmt} }} return; }}");
        let _ = writeln!(w, "        w.open(name);");
        let _ = writeln!(w, "        for x in v {{ {item_stmt} }}");
        let _ = writeln!(w, "        w.close(name);");
        let _ = writeln!(w, "    }}");
    }

    fn emit_ser_map(&mut self, s: &Shape, w: &mut String) {
        let key_m = s.key.as_ref().unwrap();
        let val_m = s.value.as_ref().unwrap();
        let key_name = key_m.get_trait("xmlName").and_then(Value::as_str).unwrap_or("key");
        let val_name = val_m.get_trait("xmlName").and_then(Value::as_str).unwrap_or("value");
        let value_ty = qualified_type(self.model, &val_m.target);
        let val_stmt = self.ser_value(&val_m.target, "x", &rust_str(val_name), false);
        let _ = writeln!(
            w,
            "    pub(super) fn {}(w: &mut XmlWriter, name: &str, v: &::std::collections::BTreeMap<String, {value_ty}>, flat: bool) {{",
            ser_fn_name(s)
        );
        let _ = writeln!(w, "        if !flat {{ w.open(name); }}");
        let _ = writeln!(w, "        for (k, x) in v {{");
        let _ = writeln!(w, "            w.open(if flat {{ name }} else {{ \"entry\" }});");
        let _ = writeln!(w, "            w.leaf({}, k);", rust_str(key_name));
        let _ = writeln!(w, "            {val_stmt}");
        let _ = writeln!(w, "            w.close(if flat {{ name }} else {{ \"entry\" }});");
        let _ = writeln!(w, "        }}");
        let _ = writeln!(w, "        if !flat {{ w.close(name); }}");
        let _ = writeln!(w, "    }}");
    }
}

fn de_fn_name(s: &Shape) -> String {
    format!("de_{}", snake_case(s.name()))
}

fn ser_fn_name(s: &Shape) -> String {
    format!("ser_{}", snake_case(s.name()))
}

/// The Rust type of `target` as seen from a sibling of the `types` module.
fn qualified_type(model: &Model, target: &str) -> String {
    let s = model.expect(target);
    match s.ty {
        ShapeType::Structure | ShapeType::Union => format!("types::{}", type_name(s.name())),
        ShapeType::List | ShapeType::Set => {
            format!("::std::vec::Vec<{}>", qualified_type(model, &s.member.as_ref().unwrap().target))
        }
        ShapeType::Map => format!(
            "::std::collections::BTreeMap<::std::string::String, {}>",
            qualified_type(model, &s.value.as_ref().unwrap().target)
        ),
        _ => crate::rust_types::scalar_type(s.ty).to_string(),
    }
}

fn error_code_and_status(s: &Shape) -> (String, u16) {
    if let Some(q) = s.get_trait("aws.protocols#awsQueryError") {
        let code = q.get("code").and_then(Value::as_str).unwrap_or(s.name()).to_string();
        let status = q.get("httpResponseCode").and_then(Value::as_u64).unwrap_or(400) as u16;
        return (code, status);
    }
    let status = s.get_trait("httpError").and_then(Value::as_u64).map(|v| v as u16).unwrap_or_else(|| {
        if s.get_trait("error").and_then(Value::as_str) == Some("server") {
            500
        } else {
            400
        }
    });
    (s.name().to_string(), status)
}

fn opt_u64(v: Option<f64>) -> String {
    v.map(|v| format!("Some({})", v as u64)).unwrap_or_else(|| "None".into())
}

fn opt_f64(v: Option<f64>) -> String {
    v.map(|v| format!("Some({v:?})")).unwrap_or_else(|| "None".into())
}
